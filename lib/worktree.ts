import { execFile } from "node:child_process";
import { createHash } from "node:crypto";
import { appendFile, lstat, mkdir, readFile, realpath, rm, stat, writeFile } from "node:fs/promises";
import os from "node:os";
import path from "node:path";
import { promisify } from "node:util";

const run = promisify(execFile);

/**
 * Where a mission's agents work.
 * - "plain": the folder itself (not a git repo, or isolation turned off).
 * - "worktree": a git worktree on its own branch, so the user's checkout and
 *   branches are never edited and the whole attempt can be thrown away.
 */
export type MissionWorkspace =
  | { kind: "plain"; path: string }
  | {
      kind: "worktree";
      /** Folder the agents work in (worktree root plus the requested sub-folder). */
      path: string;
      /** Root of the git worktree, used to discard it. */
      worktreePath: string;
      branch: string;
      baseRef: string;
      repoRoot: string;
    };

async function git(cwd: string, args: string[]): Promise<string> {
  // execFile, never a shell: paths and branch names are passed as argv.
  const { stdout } = await run("git", ["-C", cwd, ...args], { timeout: 30_000 });
  return stdout.trim();
}

async function gitOrNull(cwd: string, args: string[]): Promise<string | null> {
  try {
    return await git(cwd, args);
  } catch {
    return null;
  }
}
async function canonical(p: string): Promise<string> {
  try {
    return await realpath(p);
  } catch {
    return path.resolve(p);
  }
}


async function isDirectory(p: string): Promise<boolean> {
  try {
    return (await stat(p)).isDirectory();
  } catch {
    return false;
  }
}

/** Short, branch-safe id: "mission-1730000000000-ab12c" -> "1730000000000-ab12c". */
export function missionSlug(missionId: string): string {
  return missionId.replace(/^mission-/, "").replace(/[^A-Za-z0-9-]/g, "-").slice(0, 60);
}

export function missionBranchName(missionId: string): string {
  return `neiro/${missionSlug(missionId)}`;
}

export function worktreeRoot(env: Record<string, string | undefined> = process.env): string {
  const custom = env.NEIRO_WORKTREE_ROOT?.trim();
  return custom ? path.resolve(custom) : path.join(os.homedir(), ".neiro", "worktrees");
}

/**
 * Resolve the folder the mission's agents work in, creating an isolated
 * worktree on branch `neiro/<mission>` when the folder is a git repo.
 * Idempotent: an existing worktree for the mission is reused.
 * Runs on the Neiro server, so the path must exist on that machine (the
 * same machine Hermes runs on for the agents to reach it).
 */
export async function prepareMissionWorkspace(input: {
  workspacePath: string;
  missionId: string;
  baseBranch: string | null;
  isolate: boolean;
}): Promise<MissionWorkspace> {
  const requested = path.resolve(input.workspacePath);
  if (!(await isDirectory(requested))) {
    throw new Error(`Workspace folder not found on the Neiro server: ${requested}`);
  }

  const rawRepoRoot = await gitOrNull(requested, ["rev-parse", "--show-toplevel"]);
  if (!input.isolate || !rawRepoRoot) {
    if (input.baseBranch && !rawRepoRoot) {
      throw new Error(`base_branch was set but ${requested} is not a git repository`);
    }
    return { kind: "plain", path: requested };
  }

  const repoRoot = await canonical(rawRepoRoot);
  const canonicalRequested = await canonical(requested);
  // Keep the sub-folder the user pointed at, relative to the repo root.
  const subdir = path.relative(repoRoot, canonicalRequested);
  const branch = missionBranchName(input.missionId);

  const worktreePath = path.join(worktreeRoot(), path.basename(repoRoot), missionSlug(input.missionId));

  let baseRef = input.baseBranch;
  if (!baseRef) {
    const current = await git(repoRoot, ["rev-parse", "--abbrev-ref", "HEAD"]);
    baseRef = current === "HEAD" ? await git(repoRoot, ["rev-parse", "HEAD"]) : current;
  }

  if (await isDirectory(worktreePath)) {
    const top = await gitOrNull(worktreePath, ["rev-parse", "--show-toplevel"]);
    if (top && (await canonical(top)) === (await canonical(worktreePath))) {
      return { kind: "worktree", path: path.join(worktreePath, subdir), worktreePath, branch, baseRef, repoRoot };
    }
    throw new Error(`Worktree folder exists but is not a git worktree: ${worktreePath}`);
  }

  const baseCommit = await gitOrNull(repoRoot, ["rev-parse", "--verify", "--quiet", `${baseRef}^{commit}`]);
  if (!baseCommit) {
    throw new Error(`Base branch "${baseRef}" does not exist in ${repoRoot}`);
  }

  const branchExists = await gitOrNull(repoRoot, ["rev-parse", "--verify", "--quiet", `refs/heads/${branch}`]);
  const addArgs = branchExists
    ? ["worktree", "add", worktreePath, branch]
    : ["worktree", "add", "-b", branch, worktreePath, baseCommit];
  await git(repoRoot, addArgs);

  return { kind: "worktree", path: path.join(worktreePath, subdir), worktreePath, branch, baseRef, repoRoot };
}

const HERMES_CONTEXT_MARKER = "<!-- Generated by Neiro; do not commit. -->";

/** Write mission context only in an isolated worktree and ensure ordinary git adds ignore it. */
export async function writeWorktreeHermesContext(worktreePath: string, content: string): Promise<void> {
  const root = await git(worktreePath, ["rev-parse", "--show-toplevel"]);
  if ((await canonical(root)) !== (await canonical(worktreePath))) throw new Error("Expected the root of an isolated worktree.");
  const tracked = await git(worktreePath, ["ls-files", "--", ".hermes.md"]);
  if (tracked) throw new Error("Refusing to overwrite a tracked .hermes.md.");
  const target = path.join(root, ".hermes.md");
  try {
    const info = await lstat(target);
    if (!info.isFile() || info.isSymbolicLink() || !(await readFile(target, "utf8")).startsWith(HERMES_CONTEXT_MARKER)) {
      throw new Error("Refusing to overwrite an existing .hermes.md not created by Neiro.");
    }
  } catch (error) {
    if ((error as NodeJS.ErrnoException).code !== "ENOENT") throw error;
  }
  const exclude = await git(worktreePath, ["rev-parse", "--git-path", "info/exclude"]);
  const excludePath = path.resolve(worktreePath, exclude);
  let rules = "";
  try { rules = await readFile(excludePath, "utf8"); } catch (error) { if ((error as NodeJS.ErrnoException).code !== "ENOENT") throw error; }
  if (!rules.split(/\r?\n/).includes("/.hermes.md")) await appendFile(excludePath, "\n/.hermes.md\n");
  await git(worktreePath, ["check-ignore", "-q", "--", ".hermes.md"]);
  await writeFile(target, `${HERMES_CONTEXT_MARKER}\n${content}`, { mode: 0o600 });
}

/**
 * List the worktrees git itself has registered for a repo, by absolute path.
 * This is git's own record, so it does not depend on NEIRO_WORKTREE_ROOT — a
 * worktree created under one root is still found after the env var changes.
 */
async function registeredWorktrees(repoRoot: string): Promise<string[]> {
  const out = await git(repoRoot, ["worktree", "list", "--porcelain"]);
  const lines = out.split("\n").filter((line) => line.startsWith("worktree "));
  return Promise.all(lines.map((line) => canonical(line.slice("worktree ".length).trim())));
}

/** Verify the mission branch is clean and belongs to its registered isolated worktree. */
export async function missionWorktreeHead(repoRoot: string, worktreePath: string, branch: string): Promise<string> {
  const target = await canonical(worktreePath);
  const root = await canonical(repoRoot);
  if (!branch.startsWith("neiro/") || target === root || !(await registeredWorktrees(root)).includes(target)) throw new Error("Mission worktree is not registered or is not isolated.");
  if (await git(target, ["rev-parse", "--abbrev-ref", "HEAD"]) !== branch) throw new Error("Mission worktree is on a different branch.");
  if (await git(target, ["status", "--porcelain", "--untracked-files=normal"])) throw new Error("Mission worktree has uncommitted changes.");
  return git(target, ["rev-parse", "HEAD"]);
}

/**
 * Rollback: delete the mission worktree and its branch. The user's own
 * checkout is untouched. Uncommitted and committed work on the mission
 * branch is lost, so callers only allow it once the mission has stopped.
 */
export async function discardMissionWorktree(input: {
  repoRoot: string;
  worktreePath: string;
  branch: string;
}): Promise<void> {
  if (!input.branch.startsWith("neiro/")) {
    throw new Error(`Refusing to delete non-mission branch ${input.branch}`);
  }
  const target = await canonical(input.worktreePath);
  const repoRoot = await canonical(input.repoRoot);
  // Containment is checked against git's own registry for this repo, not a
  // volatile NEIRO_WORKTREE_ROOT, so a stale env value cannot block a discard
  // nor let one escape the repo. The main checkout is never a worktree we drop.
  const worktrees = await registeredWorktrees(repoRoot);
  if (target === repoRoot) {
    throw new Error(`Refusing to remove the main checkout: ${target}`);
  }
  if (!worktrees.includes(target)) {
    throw new Error(
      `Refusing to remove ${target}: not a registered worktree of ${repoRoot}`,
    );
  }
  if (await isDirectory(target)) {
    await git(repoRoot, ["worktree", "remove", "--force", target]);
  }
  await git(repoRoot, ["worktree", "prune"]);
  await gitOrNull(repoRoot, ["branch", "-D", input.branch]);
}

/** A mission row as the control route reads it for a worktree discard. */
export type MissionDiscardRow = {
  status: string | null;
  work_branch: string | null;
  worktree_path: string | null;
  repo_root: string | null;
};

/**
 * Decide whether a mission's worktree may be discarded, without touching the
 * database or git. Pure so the route handler's destructive branch is testable:
 * the route maps `ok:false` straight to `{ status, error }`.
 */
export function planWorktreeDiscard(
  row: MissionDiscardRow,
):
  | { ok: true; repoRoot: string; worktreePath: string; branch: string }
  | { ok: false; status: number; error: string } {
  if (!row.work_branch || !row.worktree_path || !row.repo_root) {
    return { ok: false, status: 409, error: "Mission has no worktree to discard" };
  }
  if (!["cancelled", "completed"].includes(String(row.status))) {
    return { ok: false, status: 409, error: "Cancel the mission before discarding its worktree" };
  }
  return {
    ok: true,
    repoRoot: row.repo_root,
    worktreePath: row.worktree_path,
    branch: row.work_branch,
  };
}

export type TaskWorktree = { worktreePath: string; branch: string };
export class TaskMergeConflict extends Error {
  constructor(readonly files: string[]) { super(`Task merge conflict${files.length ? `: ${files.join(", ")}` : ""}`); this.name = "TaskMergeConflict"; }
}

/** A task branch is a sibling, since Git cannot nest a branch under an existing ref. */
export async function prepareTaskWorktree(mission: Extract<MissionWorkspace, { kind: "worktree" }>, taskId: string, taskKey: string | null): Promise<TaskWorktree> {
  await missionWorktreeHead(mission.repoRoot, mission.worktreePath, mission.branch);
  const short = (taskKey || "task").replace(/[^A-Za-z0-9_-]/g, "-").slice(0, 40) || "task";
  const digest = createHash("sha256").update(taskId).digest("hex").slice(0, 10);
  const branch = `${mission.branch}-task-${short}-${digest}`;
  const folder = path.join(path.dirname(mission.worktreePath), `${path.basename(mission.worktreePath)}-tasks`, `${short}-${digest}`);
  if (await isDirectory(folder)) {
    const registered = await registeredWorktrees(mission.repoRoot);
    if (!registered.includes(path.resolve(folder)) || await git(folder, ["rev-parse", "--abbrev-ref", "HEAD"]) !== branch) throw new Error("Task worktree path is already in use.");
    return { worktreePath: folder, branch };
  }
  await mkdir(path.dirname(folder), { recursive: true });
  const exists = await gitOrNull(mission.repoRoot, ["rev-parse", "--verify", "--quiet", `refs/heads/${branch}`]);
  await git(mission.repoRoot, exists ? ["worktree", "add", folder, branch] : ["worktree", "add", "-b", branch, folder, mission.branch]);
  const context = path.join(mission.worktreePath, ".hermes.md");
  try {
    const text = await readFile(context, "utf8");
    if (text.startsWith(HERMES_CONTEXT_MARKER)) await writeWorktreeHermesContext(folder, text.slice(HERMES_CONTEXT_MARKER.length).replace(/^\n/, ""));
  } catch (error) { if ((error as NodeJS.ErrnoException).code !== "ENOENT") throw error; }
  return { worktreePath: folder, branch };
}

async function acquireTaskMergeLock(mission: Extract<MissionWorkspace, { kind: "worktree" }>): Promise<string | null> {
  const common = await git(mission.worktreePath, ["rev-parse", "--git-common-dir"]);
  const lock = path.join(path.resolve(mission.worktreePath, common), "neiro-task-merge.lock");
  try { await mkdir(lock); } catch (error) {
    if ((error as NodeJS.ErrnoException).code !== "EEXIST") throw error;
    const lockInfo = await lstat(lock).catch(() => null);
    if (lockInfo && Date.now() - lockInfo.mtimeMs > 10 * 60_000) {
      throw new Error(`Task merge lock is over 10 minutes old. Check that no Neiro merge is running, then remove ${lock} and retry.`);
    }
    return null;
  }
  return lock;
}

/** Git normally deletes ignored files when removing a clean worktree. */
async function assertTaskIgnoredFilesSafe(worktreePath: string): Promise<void> {
  const ignored = (await git(worktreePath, ["ls-files", "--others", "--ignored", "--exclude-standard", "--directory", "-z"])).split("\0").filter(Boolean);
  for (const file of ignored) {
    if (file === ".hermes.md") {
      const info = await lstat(path.join(worktreePath, file));
      if (info.isFile() && !info.isSymbolicLink() && (await readFile(path.join(worktreePath, file), "utf8")).startsWith(HERMES_CONTEXT_MARKER)) continue;
    }
    throw new Error("Task worktree contains ignored files; it was kept for inspection.");
  }
}

/** Remove only a clean, already merged task; safe to retry after interruption. */
export async function cleanupMergedTaskWorktree(mission: Extract<MissionWorkspace, { kind: "worktree" }>, task: TaskWorktree): Promise<"cleaned" | "busy"> {
  if (!task.branch.startsWith(`${mission.branch}-task-`)) throw new Error("Task branch does not belong to this mission.");
  const lock = await acquireTaskMergeLock(mission);
  if (!lock) return "busy";
  try {
    const branchExists = await gitOrNull(mission.repoRoot, ["rev-parse", "--verify", "--quiet", `refs/heads/${task.branch}`]);
    const registered = (await registeredWorktrees(mission.repoRoot)).includes(await canonical(task.worktreePath));
    if (!registered && await isDirectory(task.worktreePath)) throw new Error("Task path is not a registered worktree; it was kept for inspection.");
    if (registered) {
      if (!branchExists || await git(task.worktreePath, ["rev-parse", "--abbrev-ref", "HEAD"]) !== task.branch) throw new Error("Task worktree is on a different branch.");
      if (await git(task.worktreePath, ["status", "--porcelain", "--untracked-files=normal"])) throw new Error("Task worktree has uncommitted changes; it was kept for inspection.");
      await assertTaskIgnoredFilesSafe(task.worktreePath);
    }
    if (branchExists && await gitOrNull(mission.worktreePath, ["merge-base", "--is-ancestor", task.branch, mission.branch]) === null) throw new Error("Task branch is not merged; it was kept for inspection.");
    if (registered) await git(mission.repoRoot, ["worktree", "remove", task.worktreePath]);
    if (branchExists) await git(mission.worktreePath, ["branch", "-d", task.branch]);
    return "cleaned";
  } finally { await rm(lock, { recursive: true, force: true }); }
}

/** Commit and merge one stopped task under an inter-process Git-directory lock. */
export async function mergeTaskWorktree(mission: Extract<MissionWorkspace, { kind: "worktree" }>, task: TaskWorktree, title: string, afterMerge?: () => Promise<void>): Promise<"merged" | "busy"> {
  const target = await canonical(task.worktreePath);
  const registered = await registeredWorktrees(mission.repoRoot);
  if (!task.branch.startsWith(`${mission.branch}-task-`) || !registered.includes(target)) throw new Error("Task worktree is not registered for this mission.");
  if (await git(target, ["rev-parse", "--abbrev-ref", "HEAD"]) !== task.branch) throw new Error("Task worktree is on a different branch.");
  const lock = await acquireTaskMergeLock(mission);
  if (!lock) return "busy";
  try {
    await missionWorktreeHead(mission.repoRoot, mission.worktreePath, mission.branch);
    if (await git(task.worktreePath, ["status", "--porcelain", "--untracked-files=normal"])) {
      await git(task.worktreePath, ["add", "-A"]);
      await git(task.worktreePath, ["-c", "user.name=Neiro", "-c", "user.email=neiro@localhost", "commit", "-q", "-m", `neiro: ${title.replace(/\s+/g, " ").slice(0, 120) || "task"}`]);
    }
    const taskHead = await git(task.worktreePath, ["rev-parse", "HEAD"]);
    try { await git(mission.worktreePath, ["-c", "user.name=Neiro", "-c", "user.email=neiro@localhost", "merge", "--no-ff", "--no-edit", task.branch]); }
    catch (error) {
      const conflicts = (await gitOrNull(mission.worktreePath, ["diff", "--name-only", "--diff-filter=U"]))?.split("\n").filter(Boolean) ?? [];
      if (conflicts.length) { await git(mission.worktreePath, ["merge", "--abort"]); throw new TaskMergeConflict(conflicts); }
      throw error;
    }
    if (await git(task.worktreePath, ["rev-parse", "HEAD"]) !== taskHead || await git(task.worktreePath, ["status", "--porcelain", "--untracked-files=normal"])) throw new Error("Task worktree changed after merge; it was kept for inspection.");
    await assertTaskIgnoredFilesSafe(task.worktreePath);
    await afterMerge?.();
    if (await git(task.worktreePath, ["rev-parse", "HEAD"]) !== taskHead || await git(task.worktreePath, ["status", "--porcelain", "--untracked-files=normal"])) throw new Error("Task worktree changed after merge; it was kept for inspection.");
    await assertTaskIgnoredFilesSafe(task.worktreePath);
    await git(mission.repoRoot, ["worktree", "remove", task.worktreePath]);
    await git(mission.worktreePath, ["branch", "-d", task.branch]);
    return "merged";
  } finally { await rm(lock, { recursive: true, force: true }); }
}
